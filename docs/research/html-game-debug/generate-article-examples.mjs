import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = path.dirname(fileURLToPath(import.meta.url));
const output = path.join(root, "article-demonstrations");
fs.mkdirSync(path.join(output, "fixtures"), { recursive: true });
const labels = {
  original: ["動く基準版", "3回で勝利し、リセット後も遊べる版です。"],
  "syntax-broken": ["例1 値が抜けた版", "初期表示から敵名が空欄になり、SyntaxErrorが出る版です。"],
  "syntax-repaired": ["例1 修正版", "敵名の値を戻した版です。"],
  "selector-broken": ["例2 ボタンの取得を間違えた版", "敵名は表示されますが、TypeErrorが出てボタンが反応しない版です。"],
  "selector-repaired": ["例2 修正版", "ボタンのIDと取得する名前を合わせた版です。"],
  "reset-broken": ["例3 リセット後に攻撃できない版", "1回目は勝てます。「もう一度」の後に攻撃できない版です。"],
  "reset-repaired": ["例3 修正版", "勝利後の攻撃停止を残し、リセット時に再有効化した版です。"],
};
const examples = [];
const manifest = { source: "layout-correction/fixtures", displayChanges: ["viewport meta", "h1 font-size 1.25rem; line-height 1.4", "h1 phrase spans and wbr", "narrow iframe at <=220px: reduce main padding and heading size"], files: [] };
for (const [id, [label, note]] of Object.entries(labels)) {
  const original = fs.readFileSync(path.join(root, "layout-correction/fixtures", `${id}.html`), "utf8");
  const replacements = [
    ['  <meta charset="utf-8">', '  <meta charset="utf-8">\n  <meta name="viewport" content="width=device-width, initial-scale=1">'],
    ['    .hp {', '    h1 { font-size: 1.25rem; line-height: 1.4; }\n    h1 span { display: inline-block; }\n    .hp {'],
    ['    #fight { color: white; background: #087f5b; }', '    #fight { color: white; background: #087f5b; }\n    @media (max-width: 220px) {\n      main { width: 100%; padding: 12px 4px; }\n      h1 { font-size: 1rem; }\n      button { margin: 4px 0; padding: 8px 4px; max-width: 100%; }\n    }'],
    ['    <h1>モンスターバトル</h1>', '    <h1><span>モンスター</span><wbr><span>バトル</span></h1>'],
  ];
  let code = original;
  for (const [before, after] of replacements) {
    if (code.split(before).length !== 2) throw new Error(`Expected one display change: ${id}`);
    code = code.replace(before, after);
  }
  if (code.match(/<script>([\s\S]*?)<\/script>/)[1] !== original.match(/<script>([\s\S]*?)<\/script>/)[1]) throw new Error(`JS changed: ${id}`);
  fs.writeFileSync(path.join(output, "fixtures", `${id}.html`), code);
  examples.push({ id, label, note, code });
  manifest.files.push({ id, sha256: createHash("sha256").update(code).digest("hex") });
}
fs.writeFileSync(path.join(output, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
fs.writeFileSync(path.join(root, "../../../data/html-game-debug-examples.ts"), `// Generated by docs/research/html-game-debug/generate-article-examples.mjs.\n// Display-only changes are shared; each broken variant retains exactly one JS defect.\nexport const htmlGameDebugExamples = ${JSON.stringify(examples, null, 2)} as const;\n`);
const verification = fs.readFileSync(path.join(root, "layout-correction/verify.cjs"), "utf8").replace("Separate layout-correction evidence only.", "Separate article-demonstration evidence only.");
fs.writeFileSync(path.join(output, "verify.cjs"), verification);
