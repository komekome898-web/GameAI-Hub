    <p>相場の研究と表面は違うが、起きていることは同じだ。AIは正しい作業を速くするが、間違った作業も同じ速さで進める。だから、動くかどうかではなく「自分の目で確認できる完了条件」を先に決めておくことが効いてくる。</p>
